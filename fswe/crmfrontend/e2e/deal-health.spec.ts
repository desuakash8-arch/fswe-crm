import {test,expect} from "@playwright/test";

test("deal health explains risk, updates after actions, and stays usable on mobile",async({page,request})=>{
  test.setTimeout(60000);
  const login=await request.post("/api/auth/login",{data:{email:"sales@browser.test",password:"Browser-test-password"}});
  expect(login.ok()).toBeTruthy();const auth=await login.json();
  const headers={Authorization:`Bearer ${auth.token}`};
  const date=(offset:number)=>{const d=new Date();d.setDate(d.getDate()+offset);return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,"0")}-${String(d.getDate()).padStart(2,"0")}`;};
  const customer=await request.post("/api/customers",{headers,data:{name:"Health demo customer",status:"ACTIVE"}});
  expect(customer.ok()).toBeTruthy();const c=await customer.json();
  const deal=await request.post("/api/deals",{headers,data:{title:"Health demo opportunity",amount:60000,stage:"PROPOSAL",expectedCloseDate:date(-1),customer:{customerId:c.customerId}}});
  expect(deal.ok()).toBeTruthy();const d=await deal.json();
  await page.goto("/login");await page.locator('input[type=email]').fill("sales@browser.test");await page.locator('input[type=password]').fill("Browser-test-password");await page.locator('button[type=submit]').click();
  await expect(page.getByRole("heading",{name:"Dashboard",exact:true})).toBeVisible();
  await page.goto(`/deals/${d.dealId}/health`);
  await expect(page.getByText("At risk",{exact:true})).toBeVisible();
  await expect(page.getByRole("heading",{name:"Why this status?"})).toBeVisible();
  await expect(page.getByText(/has passed while the deal is still open/)).toBeVisible();
  await page.getByRole("button",{name:"Review closing date",exact:true}).first().click();
  await page.getByLabel("Expected closing date",{exact:true}).fill(date(10));await page.getByRole("button",{name:"Save closing date",exact:true}).click();
  await expect(page.getByText("Needs attention",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Open deal interactions",exact:true}).click();
  await page.getByRole("button",{name:"Add interaction",exact:true}).click();
  await page.getByLabel("Notes",{exact:true}).fill("Customer confirmed proposal review tomorrow.");
  await page.getByLabel("Interaction date",{exact:true}).fill(`${date(-1)}T10:00`);
  await page.getByLabel("Next follow-up",{exact:true}).fill(`${date(1)}T10:00`);
  await page.getByRole("button",{name:"Save",exact:true}).click();
  await expect(page.getByText("On track",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Deal tasks",exact:true}).click();
  await page.getByRole("button",{name:"Add task",exact:true}).click();
  await page.getByLabel("Title",{exact:true}).fill("Overdue proposal review");await page.getByLabel("Due date",{exact:true}).fill(date(-4));
  await page.getByRole("button",{name:"Save",exact:true}).click();
  await expect(page.getByText("At risk",{exact:true})).toBeVisible();await expect(page.getByText(/oldest is 4 day/)).toBeVisible();
  await expect(page.getByText("Overdue proposal review",{exact:true})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:"test-results/deal-health-light.png",fullPage:true});
  await page.getByRole("button",{name:"Dark mode",exact:true}).click();
  await page.screenshot({path:"test-results/deal-health-dark.png",fullPage:true});
  await page.getByRole("button",{name:"Light mode",exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.locator(".sidebar").evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.screenshot({path:"test-results/deal-health-mobile.png",fullPage:true,animations:"disabled"});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.getByRole("button",{name:"Edit",exact:true}).click();await page.getByRole("combobox",{name:"Status",exact:true}).selectOption("COMPLETED");
  await page.getByRole("button",{name:"Save",exact:true}).click();await expect(page.getByText("On track",{exact:true})).toBeVisible();
  await page.setViewportSize({width:1440,height:1000});
  await page.goto("/deals");const row=page.getByRole("row").filter({has:page.getByText("Health demo opportunity",{exact:true})});
  await expect(row.getByText("On track",{exact:true})).toBeVisible();
  await page.screenshot({path:"test-results/deal-health-list.png",fullPage:true});
  await page.goto("/pipeline");const card=page.locator("article").filter({has:page.getByText("Health demo opportunity",{exact:true})});
  await expect(card.getByText("On track",{exact:true})).toBeVisible();await card.getByRole("link",{name:"Why this status?"}).click();await expect(page.getByRole("heading",{name:"Deal health",exact:true})).toBeVisible();
  const closed=await request.patch(`/api/deals/${d.dealId}/stage`,{headers,data:{stage:"WON"}});expect(closed.ok()).toBeTruthy();
  await page.getByRole("button",{name:"Refresh",exact:true}).first().click();await expect(page.getByText("Closed",{exact:true})).toBeVisible();
});
