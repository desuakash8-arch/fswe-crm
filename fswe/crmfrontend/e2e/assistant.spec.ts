import {test,expect} from "@playwright/test";

test("assistant uses live scoped records for all four topics and supports editable drafts on mobile",async({page})=>{
  await page.goto("/login");await page.locator('input[type=email]').fill("assistant-sales@browser.test");await page.locator('input[type=password]').fill("Browser-test-password");await page.getByRole("button",{name:"Login",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Dashboard",exact:true})).toBeVisible();
  const records=await page.evaluate(async()=>{
    const base=await import("/src/services/apiBaseUrl.ts");
    const headers={"Content-Type":"application/json",Authorization:`Bearer ${localStorage.getItem("crmToken")}`};
    const customer=await fetch(`${base.API_BASE_URL}/customers`,{method:"POST",headers,body:JSON.stringify({name:"Assistant Customer",email:"assistant@example.invalid",status:"ACTIVE"})}).then(r=>r.json());
    const deal=await fetch(`${base.API_BASE_URL}/deals`,{method:"POST",headers,body:JSON.stringify({title:"Assistant opportunity",amount:2500,stage:"PROPOSAL",customer:{customerId:customer.customerId}})}).then(r=>r.json());
    return {customerId:customer.customerId,dealId:deal.dealId};
  });
  await page.getByRole("link",{name:"Open AI assistant"}).click();
  await expect(page.getByRole("heading",{name:"AI Assistant",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Ask assistant",exact:true}).click();
  await expect(page.locator(".assistant-answer")).toHaveCount(1);
  await expect(page.locator(".assistant-answer")).toContainText("unfinished task(s)");
  await page.getByRole("button",{name:/Customer summary Catch up/}).click();
  await page.getByLabel("Find a customer").fill("Assistant Customer");
  await page.getByLabel("Customer",{exact:true}).selectOption(String(records.customerId));
  await page.getByRole("button",{name:"Ask assistant",exact:true}).click();
  await expect(page.locator(".assistant-answer")).toHaveCount(2);
  await expect(page.locator(".assistant-answer").last()).toContainText("Assistant Customer");
  await page.getByRole("button",{name:/Deal health Understand/}).click();
  await page.getByLabel("Find a deal").fill("Assistant opportunity");
  await page.getByLabel("Deal",{exact:true}).selectOption(String(records.dealId));
  await page.getByRole("button",{name:"Ask assistant",exact:true}).click();
  await expect(page.locator(".assistant-answer")).toHaveCount(3);
  await expect(page.locator(".assistant-answer").last()).toContainText("Recorded health: NEEDS ATTENTION");
  await page.getByRole("button",{name:/Email draft Turn customer/}).click();
  await page.getByRole("button",{name:"Draft email",exact:true}).click();
  await expect(page.getByRole("region",{name:"Email draft editor"})).toBeVisible();
  await page.getByLabel("Draft subject",{exact:true}).fill("Edited follow-up subject");
  await expect(page.getByLabel("Draft subject",{exact:true})).toHaveValue("Edited follow-up subject");
  await page.getByRole("button",{name:"Copy draft",exact:true}).click();
  await expect(page.getByText(/Draft copied|Copy is unavailable/)).toBeVisible();
  await expect(page.getByRole("button",{name:"Send email",exact:true})).toHaveCount(0);
  await page.screenshot({path:"test-results/assistant-desktop.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole("button",{name:"Open menu",exact:true}).click();
  await page.getByRole("button",{name:"Dark mode",exact:true}).click();
  await page.getByRole("link",{name:"AI Assistant",exact:true}).click();
  await expect(page.locator("html")).toHaveClass(/dark-mode/);
  await page.screenshot({path:"test-results/assistant-mobile-dark.png",fullPage:true});
  await page.getByRole("button",{name:"Clear conversation",exact:true}).click();
  await expect(page.locator(".assistant-answer")).toHaveCount(0);
  await page.route("**/assistant/config",route=>route.fulfill({json:{configured:false,provider:"Groq"}}));
  await page.reload();await expect(page.getByRole("heading",{name:"AI setup is pending"})).toBeVisible();
  await expect(page.getByRole("button",{name:"Ask assistant",exact:true})).toBeDisabled();
  await page.unroute("**/assistant/config");await page.reload();
  await page.route("**/assistant/ask",route=>route.fulfill({status:429,json:{message:"Groq's usage limit was reached. Wait a minute, then try again."}}));
  await page.getByRole("button",{name:"Ask assistant",exact:true}).click();
  await expect(page.getByRole("alert")).toContainText("usage limit");
});
